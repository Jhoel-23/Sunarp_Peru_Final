import assert from 'node:assert/strict';
import { validarCampo as validar, hoyLima } from '../public/sistema/js/comun/reglas-formulario.js';
const caso = (clave, valor, extra = {}) => validar({ clave, valor, requerido: true, ...extra });
assert.ok(caso('nombre', '   '));
assert.ok(caso('nombre', '12345'));
assert.equal(caso('nombre', "María-José O’Connor"), '');
assert.equal(caso('nombre', 'J. Carlos Quispe'), '');
assert.ok(caso('nombre', '<script>alert(1)</script>'));
assert.ok(caso('dni', '1234567'));
assert.ok(caso('dni', '1234567a'));
assert.equal(caso('dni', '00123456'), '');
assert.ok(caso('celular', '812345678'));
assert.equal(caso('celular', '987654321'), '');
for (const pagina of ['0', '-1', '1.5', '1e2', 'Infinity', '16666665']) assert.ok(caso('paginas', pagina));
assert.equal(caso('paginas', '5'), '');
assert.ok(caso('correo', 'persona@dominio', { tipo: 'email' }));
assert.equal(caso('correo', 'persona+prueba@ejemplo.com', { tipo: 'email' }), '');
assert.ok(caso('contrasena', '    '));
assert.ok(caso('contrasena', '123', { minimo: 4 }));
assert.ok(caso('contrasena2', '12345', { claveOriginal: '1234' }));
assert.equal(caso('contrasena2', '1234', { claveOriginal: '1234' }), '');
assert.ok(caso('oficina', 'inventada', { opciones: ['lima', 'cusco'] }));
assert.ok(caso('fecha', '2026-02-30', { tipo: 'date' }));
assert.ok(caso('fecha', '2026-10-14', { tipo: 'date', fechaNueva: true, hoy: '2026-10-15' }));
assert.equal(caso('fecha', '2026-10-15', { tipo: 'date', fechaNueva: true, hoy: '2026-10-15' }), '');
assert.equal(hoyLima(new Date('2026-10-16T03:00:00Z')), '2026-10-15');
assert.ok(caso('referencia', '12345'));
assert.ok(caso('referencia', 'ABC123456'));
assert.equal(caso('referencia', '000123456'), '');
assert.ok(caso('codigo', '12345'));
assert.ok(caso('monto_recibido', '24.001'));
assert.ok(caso('monto_recibido', 'NaN'));
assert.ok(caso('monto_recibido', '0'));
assert.equal(caso('monto_recibido', '42.00'), '');
assert.ok(caso('mensaje', 'Muy breve', { minimo: 20, maximo: 600 }));
assert.ok(caso('declaracion', ''));
console.log('OK: formularios: espacios, nombres, DNI, celular, correo, contraseñas, fechas Lima, opciones, páginas, importes y referencias.');
