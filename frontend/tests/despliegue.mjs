import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {normalizarCatalogo} from '../src/services/api.js';
assert.equal(normalizarCatalogo(null).length,7);
assert.deepEqual(normalizarCatalogo([]),[]);
const datos=normalizarCatalogo([{id:'partida',nombre:'Consulta',categoria:'Consultas',descripcion:'Neon',precio:500,imagen_url:'https://ejemplo.com/imagen.png'}]);
assert.equal(datos.length,1);
assert.equal(datos[0].nombre,'Consulta');
assert.equal(datos[0].ruta,'/sistema/consulta-partida.html');
assert.equal(datos[0].precio,undefined,'El frontend jamás debe exponer precios del backend');
assert.equal(datos[0].imagen_url,undefined,'El directorio ya no muestra tarjetas con imágenes');
const vercel=JSON.parse(await readFile(new URL('../vercel.json',import.meta.url),'utf8'));
assert.equal(vercel.outputDirectory,'dist');
assert.equal(vercel.framework,'vite');
assert.equal(vercel.rewrites[0].destination,'/index.html');
const vite=await readFile(new URL('../vite.config.js',import.meta.url),'utf8');
assert.match(vite,/VITE_API_URL/);
assert.match(vite,/api-entorno\.js/);
console.log('OK: consulta informativa API/Neon sin importes y preparación para Vercel.');
