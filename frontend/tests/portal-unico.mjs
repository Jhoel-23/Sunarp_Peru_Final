import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const leer=p=>readFile(new URL(p,import.meta.url),'utf8');
const a=await leer('../src/App.jsx');
const inicio=await leer('../src/pages/Inicio.jsx');
const menu=await leer('../src/components/Encabezado.jsx');
const anterior=await leer('../public/sistema/index.html');
const pago=await leer('../public/sistema/js/pago/pago.js');
const pasarela=await leer('../public/sistema/js/pago/pasarela.js');
assert.match(inicio,/Su propiedad, su empresa, su historia/);
assert.match(menu,/Registros Públicos del Perú/);
assert.match(menu,/\/sistema\/login\.html/);
assert.doesNotMatch(menu,/Portal original|Volver al portal React/);
assert.doesNotMatch(a,/Portal original|Volver al portal React/);
assert.match(anterior,/url=\//);
assert.doesNotMatch(anterior,/expediente-hero|accesos__lista/);
assert.match(pago,/consultarEstadoPasarela/);
assert.match(pago,/if \(!pasarelaActiva\)/);
assert.match(pasarela,/\/pasarela\/configuracion/);
console.log('OK: inicio institucional único en React y prevalidación de la pasarela de pruebas.');
