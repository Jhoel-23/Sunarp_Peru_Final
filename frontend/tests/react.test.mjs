import assert from 'node:assert/strict';
import {readFile,stat,readdir} from 'node:fs/promises';
import {servicios,categorias,porId} from '../src/data/servicios.js';
import {normalizarCatalogo} from '../src/services/api.js';
assert.equal(servicios.length,7);
assert.ok(servicios.every(s=>!('precio' in s)&&!('precioTexto' in s)),'El directorio React no debe contener importes');
assert.ok(servicios.every(s=>s.ruta.startsWith('/sistema/')));
assert.ok(categorias.includes('Predios'));
assert.equal(porId('cita'),undefined);
assert.equal(normalizarCatalogo(null).length,7);
const remotos=normalizarCatalogo([{id:'vigencia',nombre:'Vigencia',descripcion:'Desde la API',categoria:'Certificados',precio:30,precio_referencial:30},{id:'cita',nombre:'Reserva de cita',categoria:'Atención'}]);
assert.equal(remotos.length,1);
assert.equal(remotos[0].nombre,'Vigencia');
assert.ok(!('precio' in remotos[0])&&!('precio_referencial' in remotos[0]));
const app=await readFile(new URL('../src/App.jsx',import.meta.url),'utf8');
const menu=await readFile(new URL('../src/components/Encabezado.jsx',import.meta.url),'utf8');
const inicio=await readFile(new URL('../src/pages/Inicio.jsx',import.meta.url),'utf8');
for(const contenido of [app,menu,inicio])assert.doesNotMatch(contenido,/MiniCarrito|CarritoProvider|from ['"].*\/(?:Checkout|MiPedido|Carrito)\.jsx|Registro demo|Seguimiento demo|catalogo.*precio/i);
assert.match(menu,/Iniciar sesión/);
const pagina=await readFile(new URL('../index.html',import.meta.url),'utf8');
assert.match(pagina,/src\/main\.jsx/);
await stat(new URL('../src/pages/Servicios.jsx',import.meta.url));
const archivos=await readdir(new URL('../src/pages/',import.meta.url));
for(const nombre of ['Carrito.jsx','Checkout.jsx','Catalogo.jsx','Registro.jsx','MiPedido.jsx'])assert.ok(!archivos.includes(nombre));
console.log('OK: portal React sin tarjetas de precios, carrito, checkout ni pedidos demo; módulos originales conservados.');
