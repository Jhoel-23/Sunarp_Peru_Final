import express from 'express';
import cors from 'cors';
import auth from './routes/auth.js';
import servicios from './routes/servicios.js';
import solicitudes from './routes/solicitudes.js';
import gestion from './routes/gestion.js';
import caja from './routes/caja.js';
import pasarela from './routes/pasarela.js';
import comprobantes from './routes/comprobantes.js';
import clientes from './routes/clientes.js';
import {errores} from './middlewares/error.js';
const app=express();app.disable('x-powered-by');
const permitidos=(process.env.CORS_ORIGINS||'http://127.0.0.1:5173,http://localhost:5173').split(',').map(x=>x.trim());
app.use(cors({origin:(o,cb)=>!o||permitidos.includes(o)?cb(null,true):cb(new Error('Origen no permitido'))}));
app.use(express.json({limit:'32kb'}));
app.get('/api/salud',(req,res)=>res.json({ok:true,servicio:'SUNARP Backend'}));
app.use('/api/auth',auth);app.use('/api/servicios',servicios);app.use('/api/solicitudes',solicitudes);app.use('/api/gestion',gestion);app.use('/api/caja',caja);app.use('/api/pasarela',pasarela);app.use('/api/comprobantes',comprobantes);app.use('/api/clientes',clientes);
app.use((req,res)=>res.status(404).json({error:'Ruta inexistente.'}));app.use(errores);
export {app};
